    public static function getById($id)
    {
        $all = self::getAll();
        return $all[$id] ?? null;
    }

    public static function getByName($name)
    {
        foreach (self::getAll() as $id => $cat) {
            if (strtolower($cat['name']) === strtolower($name)) {
                return $cat;
            }
        }
        return null;
    }

    public static function getSlug($idOrName)
    {
        if (is_numeric($idOrName)) {
            $cat = self::getById((int) $idOrName);
        } else {
            $cat = self::getByName($idOrName);
        }
        return $cat['slug'] ?? null;
    }
